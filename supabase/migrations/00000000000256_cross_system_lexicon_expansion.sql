-- THE CLASSIFIER'S VOCABULARY, WIDENED, and one reading of it corrected.
--
-- WHAT THIS IS AND IS NOT, restated because it has not changed. Every row
-- below is a mapping from the ways a member actually writes about her body
-- onto canonical signal names that ALREADY EXIST, in migrations 241 and
-- 251. signal_slug is a foreign key onto cross_system_signal_names, so a
-- lexicon row can only ever be another way IN to a name a coach has
-- already reviewed, and never a new name. A phrase with no row is skipped
-- rather than guessed at.
--
-- WHAT THE FIRST PASS COULD NOT HEAR, and what this adds:
--
--   SYNONYMS. Aching, sore, tight, pinching, throbbing, popping, grinding,
--   numb, tingling, burning, swollen and the rest, each with the family of
--   words people actually reach for.
--
--   TENSE AND NUMBER, which is the hurt / hurts defect generalised. That
--   bug was not one missing word, it was one missing INFLECTION across
--   every complaint verb, so the forms are generated across the whole set
--   here rather than patched one at a time.
--
--   LATERALITY AND PLACE. Sixteen more ways to say a side and sixty more
--   ways to say a place, including every body area migration 251 added.
--
--   CONTEXT. After meals, when walking, at night, in the morning, during
--   workouts, when stressed, on stairs and in the cold, which are the
--   qualifiers a coach asks for anyway.
--
--   RESOLUTION IN BOTH DIRECTIONS, and the direction that reopens it.
--   "No longer" in front, "went away" behind, and "came back" cancelling
--   either one.
--
-- THE MATCHER STAYS DETERMINISTIC. Nothing below is a model, a guess or a
-- similarity measure. Same words, same answer, every time.


-- ---------------------------------------------------------------------
-- 0. A THIRD DIRECTION FOR THE MODIFIER KIND.
--
-- Migration 249 gave negation a direction and widened this constraint to
-- two kinds. This adds the third: a word that REOPENS a complaint a
-- closing word would otherwise have shut. "My headaches stopped, but they
-- have come back" contains a closing word and is a CURRENT complaint, and
-- a matcher that only knew how to close would have filed it as settled,
-- which is the worse direction to be wrong in for exactly the reason
-- migration 249 gives.
--
-- THE CONSTRAINT IS WIDENED BEFORE THE ROWS ARE WRITTEN, which is the only
-- order that works: a check constraint refuses the insert, not the other
-- way round.
-- ---------------------------------------------------------------------
alter table cross_system_complaint_modifiers
  drop constraint cross_system_complaint_modifiers_kind_check;

alter table cross_system_complaint_modifiers
  add constraint cross_system_complaint_modifiers_kind_check
  check (kind in ('side', 'body_area', 'context', 'frequency', 'negation', 'negation_after', 'reassertion'));


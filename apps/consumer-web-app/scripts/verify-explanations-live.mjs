const FORBIDDEN = [
  'lower cross', 'lower_cross', 'lower-crossed', 'lower crossed',
  'upper cross', 'upper_cross', 'upper-crossed', 'upper crossed',
  'flat back', 'flat_back', 'forward head', 'forward_head',
  'auto-generated', 'autogenerated', 'corrective phase',
  'corrective program generator', 'generated with seed', 'detected patterns',
  'overall severity', 'worst finding', 'not yet reviewed', 'blueprint',
  'postural pattern', 'crossed pattern', 'this pattern', 'this member',
  'myofascial', 'underactive', 'overactive', 'anti-movement',
  'spinal-flexion', 'spinal flexion', 'deep-stabilizer', 'corrective work',
  'long/weak',
];
function clinicalHits(text) {
  const haystack = (text ?? '').toLowerCase();
  return FORBIDDEN.filter((phrase) => haystack.includes(phrase));
}

const results = [];
function check(name, passed, detail = '') {
  results.push({ name, passed });
  console.log(`${passed ? 'PASS' : 'FAIL'}  ${name}${detail ? ` :: ${detail}` : ''}`);
}
function note(message) {
  console.log(`      ${message}`);
}

function serviceClient() {
  const url = process.env.PROD_SUPABASE_URL;
  const keyFile = process.env.PROD_SERVICE_KEY_FILE;
  if (!url || !keyFile) return null;
  return createClient(url, readFileSync(keyFile, 'utf8').trim(), {
    auth: { persistSession: false },
  });
}

function memberClient(accessToken) {
  return createClient(
    process.env.PROD_SUPABASE_URL,
    readFileSync(process.env.PROD_ANON_KEY_FILE, 'utf8').trim(),
    {
      auth: { persistSession: false, autoRefreshToken: false },
      global: { headers: { Authorization: `Bearer ${accessToken}` } },
    }
  );
}

function addDays(iso, days) {
  const d = new Date(`${iso}T00:00:00Z`);
  d.setUTCDate(d.getUTCDate() + days);
  return d.toISOString().slice(0, 10);
}
function nextMondayOnOrAfter(iso) {
  const d = new Date(`${iso}T00:00:00Z`);
  while (d.getUTCDay() !== 1) d.setUTCDate(d.getUTCDate() + 1);
  return d.toISOString().slice(0, 10);
}

